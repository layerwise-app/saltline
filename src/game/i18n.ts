const DICTS: Record<Lang, Dict> = { en, zh, es, de, fr };

function isLang(value: unknown): value is Lang {
  return typeof value === 'string' && value in DICTS;
}

function detectLang(): Lang {
  if (typeof window === 'undefined') return 'en';
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (isLang(stored)) return stored;
  } catch {}
  const preferred = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  for (const tag of preferred) {
    const base = String(tag || '').toLowerCase().split('-')[0];
    if (isLang(base)) return base;
  }
  return 'en';
}

let current: Lang | null = null;

/** The active language (detected once per page load). */
export function getLang(): Lang {
  if (!current) {
    current = detectLang();
    if (typeof document !== 'undefined') document.documentElement.lang = LOCALES[current];
  }
  return current;
}

/** BCP 47 locale of the active language, for number formatting. */
export function getLocale(): string {
  return LOCALES[getLang()];
}

/** Saves the language and reloads the game so every screen is rebuilt in it. */
export function setLang(lang: Lang): void {
  if (lang === getLang()) return;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {}
  location.reload();
}

/** Translates `key`, replacing `{name}` placeholders with `vars`. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let text = DICTS[getLang()][key] ?? en[key];
  if (vars) {
    for (const name in vars) text = text.split(`{${name}}`).join(String(vars[name]));
  }
  return text;
}
